import { writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

import {
  interactiveVisualizeLibrary,
  staticVisualizeLibrary,
} from "../src/features/agent-message/render-ui/library.tsx"

function writeSpec(
  library: typeof staticVisualizeLibrary,
  filename: string,
  exportName: string,
) {
  const prompt = library.toSpec()
  const spec = {
    root: library.root,
    components: prompt.components,
    ...(prompt.componentGroups === undefined ? {} : { componentGroups: prompt.componentGroups }),
    schema: library.toJSONSchema(),
  }
  const target = fileURLToPath(
    new URL(`../../services/agent-runner/ts/src/core/tool/${filename}`, import.meta.url),
  )
  writeFileSync(
    target,
    `// Generated by agent-ui/scripts/generate-render-ui-spec.ts. Do not edit.
import type { LibraryJSONSchema, LibrarySpec } from "@openuidev/lang-core"

export const ${exportName} = ${JSON.stringify(spec, null, 2)} as LibrarySpec & {
  schema: LibraryJSONSchema
}
`,
  )
}

writeSpec(staticVisualizeLibrary, "static-visualize.spec.ts", "staticVisualizeSpec")
writeSpec(interactiveVisualizeLibrary, "interactive-visualize.spec.ts", "interactiveVisualizeSpec")

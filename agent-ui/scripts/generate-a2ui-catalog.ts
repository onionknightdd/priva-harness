import { mkdirSync, writeFileSync } from "node:fs"
import { dirname } from "node:path"
import { fileURLToPath } from "node:url"

import { a2uiCatalogDefinition } from "../src/features/agent-message/a2ui/catalog-definition.ts"

const target = fileURLToPath(
  new URL("../../services/agent-runner/ts/src/core/a2ui/catalog.generated.ts", import.meta.url),
)

mkdirSync(dirname(target), { recursive: true })
writeFileSync(
  target,
  `// Generated by agent-ui/scripts/generate-a2ui-catalog.ts. Do not edit.
export const a2uiCatalogDefinition: Record<string, unknown> = ${JSON.stringify(a2uiCatalogDefinition, null, 2)}
`,
)
